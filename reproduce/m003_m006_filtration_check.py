"""
m003_m006_filtration_check.py
=============================
Independent recomputation of the collision-ideal filtration J_L (words of
length <= L) for the geometric components of m003 and m006, checking the table
in the Claude Doc "Collision Ideal Length Bounds: m003 and m006" (Oct 30 2026,
written in a separate session; its numbers were taken here as a hypothesis,
not a result).

Chart (as in the paper / m003_collision_ideal_certificate.py):
    A = [[x,-1],[1,0]],  B = [[0,-u],[-z-u,y]],  u^2 + z*u + 1 = 0,
    x = tr a, y = tr b, z = tr ab.
J_L = ideal generated by Delta_{w,v} = tau_w - tau_v over reduced words
|w|,|v| <= L (proper powers included) with Delta in P, the ideal of the
component; "colliding pair" = unordered pair {w,v}, w != v, with
Delta nonzero and in P.
Components (from the paper):
    m003: P0   = <xz+1, x^2+y-1>,     K = <x^2-xz+y-2, yz-x-z>
    m006: P006 = <x-z, y z^2 - y - 1>, K = <x-z, (y-2)(y z^2 - y - 1)>

Scope of this check: reduced words of length <= 4 in F_2 only. Same chart as
the Doc's "route 2"; the Doc's interpolation route (route 1) is not re-run.

Exit status: 0 iff every assertion on the expected table holds.
"""
import itertools
import sys
import time

import sympy as sp
from sympy import Matrix, eye, groebner, rem, symbols

x, y, z, u = symbols("x y z u")
RED = u**2 + z * u + 1

A = Matrix([[x, -1], [1, 0]]); Ai = Matrix([[0, 1], [-1, x]])
B = Matrix([[0, -u], [-z - u, y]]); Bi = Matrix([[y, u], [z + u, 0]])
GEN = {"a": A, "A": Ai, "b": B, "B": Bi}
INV = {"a": "A", "A": "a", "b": "B", "B": "b"}

# expected[component][L] = (words<=L, colliding pairs, J_L == K ?)
EXPECTED = {
    "m003": {1: (4, 0, False), 2: (16, 0, False), 3: (52, 36, True), 4: (160, 204, True)},
    "m006": {1: (4, 0, False), 2: (16, 8, False), 3: (52, 48, False), 4: (160, 328, True)},
}
FAILS = []


def check(label, ok):
    print(("PASS  " if ok else "FAIL  ") + label)
    if not ok:
        FAILS.append(label)


def red(e):
    return sp.expand(rem(sp.expand(e), RED, u))


def words(maxlen):
    out = {1: list("aAbB")}
    for L in range(2, maxlen + 1):
        out[L] = [w + c for w in out[L - 1] for c in "aAbB" if INV[c] != w[-1]]
    return out


def trace_table(maxlen):
    ws = words(maxlen)
    mats = {"": eye(2)}
    tau = {}
    for L in range(1, maxlen + 1):
        for w in ws[L]:
            mats[w] = (mats[w[:-1]] * GEN[w[-1]]).applyfunc(red)
            t = red(mats[w][0, 0] + mats[w][1, 1])
            assert not t.has(u), (w, t)
            tau[w] = t
    return ws, tau


def run(name, Pgens, Kgens, maxlen=4):
    print(f"\n===== {name} =====")
    ws, tau = trace_table(maxlen)
    Pgb = groebner(Pgens, x, y, z, order="grevlex")
    Kgb = groebner(Kgens, x, y, z, order="grevlex")
    for L in range(1, maxlen + 1):
        wle = [w for l in range(1, L + 1) for w in ws[l]]
        diffs, pairs = {}, 0
        for w, v in itertools.combinations(wle, 2):
            d = sp.expand(tau[w] - tau[v])
            if d != 0 and Pgb.contains(d):
                pairs += 1
                key = d if sp.Poly(d, x, y, z).LC() > 0 else -d
                diffs[sp.expand(key)] = (w, v)
        if diffs:
            JL = groebner(list(diffs), x, y, z, order="grevlex")
            equals_k = JL.exprs == Kgb.exprs
            gens = JL.exprs
        else:
            equals_k, gens = False, "(0)"
        print(f"L={L}: words<=L={len(wle)}  colliding pairs={pairs}  "
              f"distinct nonzero diffs={len(diffs)}  J_L==K: {equals_k}  J_L={gens}")
        ew, ep, ek = EXPECTED[name][L]
        check(f"{name} L={L}: (words, pairs, J_L==K) == {(ew, ep, ek)}",
              (len(wle), pairs, equals_k) == (ew, ep, ek))
        sys.stdout.flush()


if __name__ in ("__main__",):
    t0 = time.time()
    run("m003", [x * z + 1, x**2 + y - 1], [x**2 - x * z + y - 2, y * z - x - z])
    run("m006", [x - z, y * z**2 - y - 1], [x - z, (y - 2) * (y * z**2 - y - 1)])
    print(f"\ntotal {time.time() - t0:.0f}s")
    print("FILTRATION CHECK:", "PASS" if not FAILS else f"FAIL ({len(FAILS)})")
    sys.exit(1 if FAILS else 0)
